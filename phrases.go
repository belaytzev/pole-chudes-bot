type deck struct {
	left []int
	last int
}

var (
	decksMu sync.Mutex
	decks   = map[*string]*deck{}
)

// pick deals a pool like a shuffled deck: a phrase comes back only after the rest of the pool was used.
func pick(pool []string) string {
	decksMu.Lock()
	defer decksMu.Unlock()
	d := decks[&pool[0]]
	if d == nil {
		d = &deck{last: -1}
		decks[&pool[0]] = d
	}
	if len(d.left) == 0 {
		d.left = rand.Perm(len(pool))
		if n := len(d.left) - 1; n > 0 && d.left[n] == d.last {
			d.left[0], d.left[n] = d.left[n], d.left[0]
		}
	}
	d.last = d.left[len(d.left)-1]
	d.left = d.left[:len(d.left)-1]
	return pool[d.last]
}

