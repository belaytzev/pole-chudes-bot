// yearsWord inflects «год» for the anniversary greeting.
func yearsWord(n int) string {
	switch {
	case n%100 >= 11 && n%100 <= 14:
		return "лет"
	case n%10 == 1:
		return "год"
	case n%10 >= 2 && n%10 <= 4:
		return "года"
	}
	return "лет"
}
